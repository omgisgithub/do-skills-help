from semver_range import satisfies, max_satisfying

YES = [
    ("1.2.3", "^1.2.3"), ("v1.9.0", "^1.2.3"), ("1.2.3-beta.4", "^1.2.3-beta.2"),
    ("0.2.9", "^0.2.3"), ("0.0.3", "^0.0.3"), ("0.0.9", "^0"), ("0.0.9", "^0.x"),
    ("1.2.9", "~1.2"), ("1.9.9", "1.x"), ("1.2.5", "1.2.*"), ("5.0.0", "*"), ("5.0.0", ""),
    ("2.0.0", ">1.2"), ("1.3.0", ">1.2"), ("1.2.0", ">=1.2"), ("1.1.9", "<1.2"),
    ("1.2.9", "<=1.2"), ("2.3.4", "1.2.3 - 2.3.4"), ("2.3.9", "1.2.3 - 2.3"),
    ("3.9.9", "1.2.3 - 3"), ("1.2.3", ">= 1.2.3"), ("1.2.3+b", "1.2.3"), ("3.0.0", "1 || 3"),
    ("1.0.0-rc.1", ">=1.0.0-beta"), ("1.2.3", "=1.2.3"), ("1.5.0", "1.2 - 2.3.4"),
]
NO = [
    ("1.2.4-alpha", "^1.2.3"), ("1.0.0-rc.1", "*"), ("2.0.0", "^1.2.3"), ("2.0.0-0", "^1.2.3"),
    ("0.0.4", "^0.0.3"), ("1.2.3", ">*"), ("1.2.3", "<*"), ("1.3.0", "~1.2.3"),
    ("1.2.2", "1.2.3 - 2"), ("1.2.3-beta.1", "^1.2.3-beta.2"), ("1.3.0", "<=1.2 >1.2.5"),
]
BAD = ["~>1.2", ">=1.2.3 -", "1.2.3.4", "^", ">=a.b.c", "1.x.3", "01.2.3", "1.2-beta", "1.2.3 -2.3.4"]

for v, r in YES:
    assert satisfies(v, r), (v, r)
for v, r in NO:
    assert not satisfies(v, r), (v, r)
for r in BAD:
    try:
        satisfies("1.2.3", r)
    except ValueError:
        continue
    raise AssertionError(r)
for v in ["1.2", "01.2.3", "1.0.0-01", "1.0.0-", "vv1.0.0", "1.0.0+"]:
    try:
        satisfies(v, "*")
    except ValueError:
        continue
    raise AssertionError(v)

assert max_satisfying(["1.0.0", "1.2.0+b", "bad", "1.2.0+a", "2.0.0"], "^1") == "1.2.0+b"
assert max_satisfying(["3.0.0"], "^1") is None
order = "1.0.0-alpha 1.0.0-alpha.1 1.0.0-alpha.beta 1.0.0-beta 1.0.0-beta.2 1.0.0-beta.11 1.0.0-rc.1 1.0.0".split()
assert max_satisfying(order[::-1], ">=1.0.0-alpha") == "1.0.0"
assert max_satisfying(order[:-1][::-1], ">=1.0.0-alpha <1.0.0") == "1.0.0-rc.1"
print("ok")
